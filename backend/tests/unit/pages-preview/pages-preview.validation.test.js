import { describe, it, expect } from "vitest";
import { previewTokenParamSchema } from "../../../src/modules/pages-preview/pages-preview.validation.js";

describe("Pages Preview Validation Schema", () => {
  describe("previewTokenParamSchema", () => {
    
    it("TC-01: should pass validation for a valid token meeting the minimum length (>= 24 chars)", () => {
      const validPayload = { token: "a".repeat(24) };
      const result = previewTokenParamSchema.safeParse(validPayload);
      
      expect(result.success).toBe(true);
    });

    it("TC-02: should pass validation for the actual 64-character token generated by the service", () => {
      const hexToken = "a".repeat(64); 
      const result = previewTokenParamSchema.safeParse({ token: hexToken });
      
      expect(result.success).toBe(true);
    });

    it("TC-03: should fail validation if token is too short (< 24 chars)", () => {
      const shortPayload = { token: "short_token_123" };
      const result = previewTokenParamSchema.safeParse(shortPayload);
      
      expect(result.success).toBe(false);
      expect(result.error.issues[0].message).toBe("Invalid preview token structure");
    });

    it("TC-04: should fail validation for an empty string", () => {
      const emptyPayload = { token: "" };
      const result = previewTokenParamSchema.safeParse(emptyPayload);
      
      expect(result.success).toBe(false);
      expect(result.error.issues[0].message).toBe("Invalid preview token structure");
    });

    it("TC-05: should fail validation if token is missing completely", () => {
      const missingPayload = {}; // No token field
      const result = previewTokenParamSchema.safeParse(missingPayload);
      
      expect(result.success).toBe(false);
      expect(result.error.issues[0].path).toContain("token");
      expect(result.error.issues[0].message).toBe("Invalid input: expected string, received undefined");
    });

    it("TC-06: should fail validation if token is of incorrect type (e.g., number)", () => {
      const invalidTypePayload = { token: 123456789012345678901234n };
      const result = previewTokenParamSchema.safeParse(invalidTypePayload);
      
      expect(result.success).toBe(false);
      expect(result.error.issues[0].message).toBe("Invalid input: expected string, received bigint");
    });
    
    it("TC-07: should strip unknown fields if strict mode is not enforced (Zod default behavior)", () => {
      const extraFieldsPayload = { token: "a".repeat(24), maliciousField: "drop_table" };
      const result = previewTokenParamSchema.safeParse(extraFieldsPayload);
      
      expect(result.success).toBe(true);
      expect(result.data).not.toHaveProperty("maliciousField");
    });
    
  });
});